/*
 * Служебный работник — ровно настолько, насколько его требует установка.
 *
 * Chrome не предлагает «добавить на главный экран», пока у страницы нет
 * зарегистрированного работника с обработчиком fetch. Это и есть
 * единственная причина, по которой файл существует.
 *
 * Кэша здесь нет намеренно. Приложение обновляется пересборкой образа, и
 * закэшированный работником старый JS означал бы, что после обновления
 * человек видит вчерашнюю версию, а починка — «очистите данные сайта»,
 * которую по телефону не объяснить. Цена отказа от кэша — отсутствие
 * работы без сети; для учёта, который всё равно ходит к своему серверу за
 * каждой цифрой, это не потеря.
 */
self.addEventListener("install", () => {
  // Новый работник заступает сразу, не дожидаясь закрытия всех вкладок.
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("fetch", (event) => {
  // Просто пропускаем запрос дальше. Обработчик обязан существовать, но
  // делать ему здесь нечего.
  event.respondWith(fetch(event.request));
});
