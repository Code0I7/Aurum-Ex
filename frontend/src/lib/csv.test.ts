import { describe, expect, it } from "vitest";
import { parseAmount, parseCsv, parseDateWithFormat } from "@/lib/csv";

/**
 * Разбор банковской выписки.
 *
 * Самое дорогое место во всём фронтенде: ошибка здесь не падает и не
 * подсвечивается, она молча заводит операцию не той суммой или не того
 * числа. Дальше эта операция живёт в истории годами и портит каждый итог,
 * в который попадает.
 */

describe("parseCsv", () => {
  it("делит строки и поля", () => {
    expect(parseCsv("дата,сумма\n01.02.2026,100\n")).toEqual([
      ["дата", "сумма"],
      ["01.02.2026", "100"],
    ]);
  });

  it("не режет поле по запятой внутри кавычек", () => {
    // Ровно так выгружается русская сумма: «1 234,56» в кавычках. Без
    // учёта кавычек строка разъезжается на одно поле, и вся остальная
    // выписка читается со сдвигом на колонку.
    expect(parseCsv('описание,сумма\n"Кофе, большой","1234,56"\n')).toEqual([
      ["описание", "сумма"],
      ["Кофе, большой", "1234,56"],
    ]);
  });

  it("понимает удвоенную кавычку как одну", () => {
    expect(parseCsv('a\n"он сказал ""да"""\n')).toEqual([["a"], ['он сказал "да"']]);
  });

  it("держит перевод строки внутри поля", () => {
    expect(parseCsv('note\n"первая\nвторая"\n')).toEqual([["note"], ["первая\nвторая"]]);
  });

  it("сам определяет точку с запятой как разделитель", () => {
    // Выгрузки европейских банков разделяют точкой с запятой именно
    // потому, что запятая у них занята десятичным знаком.
    expect(parseCsv("дата;сумма\n01.02.2026;1,50\n")).toEqual([
      ["дата", "сумма"],
      ["01.02.2026", "1,50"],
    ]);
  });

  it("выбирает разделитель по первой строке, а не по всему файлу", () => {
    const rows = parseCsv("a,b,c\n1,2,3\n");
    expect(rows[1]).toEqual(["1", "2", "3"]);
  });

  it("не считает пустые строки за записи", () => {
    // Выгрузка почти всегда заканчивается переводом строки, а иногда и
    // несколькими: лишняя запись из ничего — это операция без даты и суммы.
    expect(parseCsv("a,b\n1,2\n\n\n")).toEqual([
      ["a", "b"],
      ["1", "2"],
    ]);
  });

  it("читает файл с переводом строки в виде CRLF", () => {
    expect(parseCsv("a,b\r\n1,2\r\n")).toEqual([
      ["a", "b"],
      ["1", "2"],
    ]);
  });

  it("не теряет последнюю строку без перевода в конце", () => {
    expect(parseCsv("a,b\n1,2")).toEqual([
      ["a", "b"],
      ["1", "2"],
    ]);
  });

  it("сохраняет пустое поле, а не выбрасывает его", () => {
    // Пропущенная категория — это пропущенная категория, а не сдвиг
    // остальных полей влево.
    expect(parseCsv("a,b,c\n1,,3\n")[1]).toEqual(["1", "", "3"]);
  });
});

describe("parseDateWithFormat", () => {
  it("разбирает каждый из поддерживаемых видов", () => {
    expect(parseDateWithFormat("2026-02-01", "YYYY-MM-DD")).toBe("2026-02-01");
    expect(parseDateWithFormat("01.02.2026", "DD.MM.YYYY")).toBe("2026-02-01");
    expect(parseDateWithFormat("01/02/2026", "DD/MM/YYYY")).toBe("2026-02-01");
    expect(parseDateWithFormat("01-02-2026", "DD-MM-YYYY")).toBe("2026-02-01");
  });

  it("различает день с месяцем там, где строка одинаковая", () => {
    // «03/04/2026» — это третье апреля или четвёртое марта, и данные об
    // этом не говорят. Поэтому вид выбирает человек, а разбор ему верит.
    expect(parseDateWithFormat("03/04/2026", "DD/MM/YYYY")).toBe("2026-04-03");
    expect(parseDateWithFormat("03/04/2026", "MM/DD/YYYY")).toBe("2026-03-04");
  });

  it("добавляет ведущие нули", () => {
    expect(parseDateWithFormat("1.2.2026", "DD.MM.YYYY")).toBe("2026-02-01");
  });

  it("отказывается от даты, которой не существует", () => {
    // 30 февраля Date молча превращает во второе марта. Операция уехала бы
    // на другой месяц, а предупреждения не было бы никакого.
    expect(parseDateWithFormat("30.02.2026", "DD.MM.YYYY")).toBeNull();
    expect(parseDateWithFormat("31.04.2026", "DD.MM.YYYY")).toBeNull();
    expect(parseDateWithFormat("00.01.2026", "DD.MM.YYYY")).toBeNull();
    expect(parseDateWithFormat("01.13.2026", "DD.MM.YYYY")).toBeNull();
  });

  it("принимает 29 февраля в високосном году и отвергает в обычном", () => {
    expect(parseDateWithFormat("29.02.2024", "DD.MM.YYYY")).toBe("2024-02-29");
    expect(parseDateWithFormat("29.02.2026", "DD.MM.YYYY")).toBeNull();
  });

  it("не принимает чужой вид и мусор", () => {
    expect(parseDateWithFormat("01.02.2026", "YYYY-MM-DD")).toBeNull();
    expect(parseDateWithFormat("вчера", "DD.MM.YYYY")).toBeNull();
    expect(parseDateWithFormat("", "DD.MM.YYYY")).toBeNull();
  });

  it("не спотыкается о пробелы по краям", () => {
    expect(parseDateWithFormat("  01.02.2026  ", "DD.MM.YYYY")).toBe("2026-02-01");
  });
});

describe("parseAmount", () => {
  it("читает целое и дробное", () => {
    expect(parseAmount("100")).toBe(100);
    expect(parseAmount("100.50")).toBe(100.5);
    expect(parseAmount("100,50")).toBe(100.5);
  });

  it("разбирает оба порядка разделителей", () => {
    // Решает тот знак, который стоит последним: до него — разделитель
    // тысяч, после — десятичная часть. Иначе «1.234,56» прочитается как
    // одна целая двести тридцать четыре.
    expect(parseAmount("1.234,56")).toBe(1234.56);
    expect(parseAmount("1,234.56")).toBe(1234.56);
  });

  it("не считает одиночную точку разделителем тысяч", () => {
    expect(parseAmount("1.5")).toBe(1.5);
  });

  it("убирает разделители тысяч, включая неразрывный пробел", () => {
    // Неразрывный пробел — то, что реально приезжает из таблиц: обычный
    // Number на нём возвращает NaN, и строка выпала бы из импорта.
    expect(parseAmount("12 700,00")).toBe(12700);
    expect(parseAmount("12 700,00")).toBe(12700);
  });

  it("держит минус: в выписке он и означает расход", () => {
    expect(parseAmount("-250,40")).toBe(-250.4);
  });

  it("возвращает null на пустом и на нечисле", () => {
    // null отличается от нуля: ноль означал бы операцию на нулевую сумму,
    // а здесь суммы просто нет, и строку надо показать человеку.
    expect(parseAmount("")).toBeNull();
    expect(parseAmount("   ")).toBeNull();
    expect(parseAmount("много")).toBeNull();
  });
});
