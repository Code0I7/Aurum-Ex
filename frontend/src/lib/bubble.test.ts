import { describe, expect, it } from "vitest";
import { horizontalShift } from "@/lib/bubble";

/**
 * Сдвиг пузыря, чтобы он влез в экран.
 *
 * Расчёт вынесен из компонентов именно для того, чтобы его можно было
 * проверить: измерить живой элемент в этих тестах нечем, а ошибиться знаком
 * здесь легче всего — и ошибка выглядит как подсказка, уехавшая за край, то
 * есть видна только на телефоне и только у правого края.
 */

describe("horizontalShift", () => {
  it("влезающий пузырь не двигает", () => {
    expect(horizontalShift({ left: 100, right: 300 }, 1000, 8)).toBe(0);
  });

  it("упёршийся в правый край сдвигает влево ровно на выступ", () => {
    // Правый край на 1010 при экране 1000 и отступе 8: вылез на 18.
    expect(horizontalShift({ left: 800, right: 1010 }, 1000, 8)).toBe(-18);
  });

  it("упёршийся в левый край сдвигает вправо", () => {
    // Пузырь центрируется по содержимому и может уйти за левый край.
    expect(horizontalShift({ left: -20, right: 180 }, 1000, 8)).toBe(28);
  });

  it("учитывает отступ, а не просто край экрана", () => {
    // Ровно у края — уже не влез: отступ на то и нужен, чтобы пузырь не
    // прилипал к рамке.
    expect(horizontalShift({ left: 500, right: 1000 }, 1000, 8)).toBe(-8);
    expect(horizontalShift({ left: 0, right: 200 }, 1000, 8)).toBe(8);
  });

  it("пузырь шире экрана прижимает к левому краю", () => {
    // Влезть он не может, и выбор между краями: читают слева направо, и
    // начало важнее конца. Сдвиг вправо от левого края, а не влево от
    // правого.
    expect(horizontalShift({ left: -50, right: 1200 }, 1000, 8)).toBe(58);
  });

  it("нулевой отступ допустим и означает «вплотную к краю»", () => {
    expect(horizontalShift({ left: 800, right: 1000 }, 1000, 0)).toBe(0);
    expect(horizontalShift({ left: 900, right: 1100 }, 1000, 0)).toBe(-100);
  });

  it("на узком экране телефона считает так же", () => {
    // 375 точек, пузырь шириной 288 открыт у правого края.
    expect(horizontalShift({ left: 200, right: 488 }, 375, 8)).toBe(-121);
  });
});
