import type { QueryClient } from "@tanstack/react-query";

/**
 * Что перезапрашивать после правки денег.
 *
 * Раньше у каждого хука был свой список «что от этого устарело», и списки
 * разъезжались с приложением. Перевод операции из «безвозвратно» в «прошло
 * через меня» меняет расчёты с людьми — а список о них не знал, и вкладка
 * «Долги» показывала прежнее число до перезагрузки страницы или до того
 * момента, когда окно получит фокус. Балансы счетов были той же историей:
 * операция их меняет, а в списке они не упоминались. Ни то, ни другое не
 * выглядит ошибкой — выглядит подвисшим числом, и человек первым делом
 * идёт проверять, сохранилось ли вообще.
 *
 * Поэтому список перевёрнут: перезапрашивается всё, кроме того, на что
 * деньги повлиять не могут. Забыть добавить сюда новый запрос теперь
 * нельзя — новое покрывается по умолчанию, а ошибиться можно только в
 * сторону лишнего запроса, а не устаревшего числа.
 *
 * Цена этого «всего» меньше, чем кажется: React Query перезапрашивает
 * только те запросы, что прямо сейчас показаны на экране, а остальные
 * помечает устаревшими и тянет, когда до них дойдёт очередь. То есть цена
 * равна цене того, что человек и так видит, — это десяток запросов по
 * 3–35 мс.
 */

/**
 * Запросы, которых деньги не касаются.
 *
 * Два повода попасть сюда, и оба должны быть названы: справочник без сумм
 * или запрос, который стоит дорого.
 */
const NOT_ABOUT_MONEY = [
  // Справочники и настройки: сумм в них нет вовсе.
  "settings",
  "banks",
  "units",
  "health",
  // Цены криптовалют тянутся из CoinGecko по сети, и обновлять их из-за
  // правки продуктового чека значило бы платить секундой ожидания за
  // число, которое не изменилось. Свои крипто-сделки живут отдельным
  // журналом и от операций по счетам не зависят.
  "crypto-holdings",
  "crypto-history",
  "crypto-performance-90d",
  "crypto-portfolios",
  "crypto-transactions",
];

/**
 * Помечает устаревшим всё, что могло измениться от движения денег.
 *
 * Зовётся после правки операции, счёта, цели — всего, что меняет суммы.
 * Одна функция на всех намеренно: три копии списка в трёх хуках и довели до
 * того, что две из них забыли про расчёты с людьми.
 */
export function invalidateMoneyQueries(queryClient: QueryClient): void {
  queryClient.invalidateQueries({
    predicate: (query) => !NOT_ABOUT_MONEY.includes(String(query.queryKey[0])),
  });
}
