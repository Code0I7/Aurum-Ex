/**
 * Чтобы пузырь не уехал за край экрана.
 *
 * Подсказка открывается от своего места — от значка, от числа в колонке, —
 * и у правого края экрана уходит за него: прочитать можно только начало.
 * Поэтому после открытия она меряется и сдвигается ровно настолько, чтобы
 * поместиться, но не левее экрана.
 *
 * Расчёт вынесен из компонентов в отдельную чистую функцию по двум
 * причинам. Первая: таких пузырей больше одного, и вторая копия этой
 * арифметики разошлась бы с первой при первой же правке. Вторая: здесь легко
 * ошибиться знаком, а проверить измерение живого элемента нечем — зато
 * саму арифметику проверить можно.
 */

/** Насколько сдвинуть пузырь по горизонтали, чтобы он влез в экран.
 *
 * Ноль — уже влез. Отрицательное — подвинуть влево (упёрся в правый край),
 * положительное — вправо (упёрся в левый). Если пузырь шире экрана, левый
 * край побеждает: читают слева направо, и начало важнее конца.
 *
 * Всё в одних единицах — тех же, в которых пришли `left`, `right` и
 * `viewportWidth`. Перевод в единицы разметки делается снаружи, один раз,
 * чтобы здесь не оказалось двух разных пикселей (см. lib/scale.ts).
 */
export function horizontalShift(
  bubble: { left: number; right: number },
  viewportWidth: number,
  margin: number
): number {
  let shift = 0;
  const overflowRight = bubble.right - (viewportWidth - margin);
  if (overflowRight > 0) shift = -overflowRight;
  if (bubble.left + shift < margin) shift = margin - bubble.left;
  return shift;
}
