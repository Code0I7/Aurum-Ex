import { beforeEach, describe, expect, it } from "vitest";
import { formatWorkCost, rateForDate, type HourlyRates } from "@/lib/hours";
import { setLanguage } from "@/lib/i18n";

/**
 * Цена покупки в рабочем времени.
 *
 * Смысл не в цифре, а в единице: «четыре рабочих дня» доходит быстрее, чем
 * «17 273 ₽». Поэтому проверяется выбор единицы и то, что отсутствие ставки
 * даёт «посчитать не из чего», а не ноль — ноль означал бы, что покупка
 * досталась даром.
 */

beforeEach(() => {
  setLanguage("ru");
});

const RATES: HourlyRates = {
  months: { "2026-01": "500", "2026-02": "600" },
  overall: "400",
};

describe("rateForDate", () => {
  it("берёт ставку того месяца, в котором была покупка", () => {
    // Не сегодняшнюю: за несколько лет заработок меняется в разы, и старая
    // покупка по нынешней ставке выглядела бы втрое дешевле, чем была.
    expect(rateForDate(RATES, "2026-01-15")).toBe(500);
    expect(rateForDate(RATES, "2026-02-01")).toBe(600);
  });

  it("месяц отрезается от строки, а не считается из даты", () => {
    // Разбор даты втянул бы часовой пояс, и покупка первого числа съезжала
    // бы в предыдущий месяц вместе со своей ставкой.
    expect(rateForDate(RATES, "2026-02-01")).toBe(600);
    expect(rateForDate(RATES, "2026-02-28")).toBe(600);
  });

  it("месяц без своей ставки падает на среднюю за всё время", () => {
    // Человек работал и тогда — просто в скользящем окне не набралось часов.
    expect(rateForDate(RATES, "2025-07-10")).toBe(400);
  });

  it("без ставок вовсе отвечает «не из чего»", () => {
    expect(rateForDate({ months: {}, overall: null }, "2026-01-15")).toBeNull();
    expect(rateForDate(undefined, "2026-01-15")).toBeNull();
  });

  it("нулевую ставку считает отсутствием ставки", () => {
    // Ноль рублей в час — не ставка, а незаполненные часы: делить на него
    // нельзя, и «бесконечно дорого» на экране не нужно.
    expect(rateForDate({ months: { "2026-01": "0" }, overall: null }, "2026-01-15")).toBeNull();
  });
});

describe("formatWorkCost", () => {
  it("мелочь показывает минутами", () => {
    // «0,03 дня» за проезд на автобусе так же бесполезно, как «112 часов»
    // за монитор.
    expect(formatWorkCost(250, 500)).toBe("30 мин");
  });

  it("до рабочего дня — часами с десятой долей", () => {
    expect(formatWorkCost(1000, 500)).toBe("2,0 ч");
    expect(formatWorkCost(2100, 500)).toBe("4,2 ч");
  });

  it("от рабочего дня — днями", () => {
    // День считается восьмичасовым: не догма, но понятнее, чем спрашивать
    // длину смены.
    expect(formatWorkCost(4000, 500)).toBe("1,0 дн");
    expect(formatWorkCost(17273, 500)).toBe("4,3 дн");
  });

  it("дальше десяти дней округляет до дня", () => {
    // «23,4 дня» точнее, чем нужно, чтобы ужаснуться.
    expect(formatWorkCost(100000, 500)).toBe("25 дн");
  });

  it("смотрит на величину, а не на знак", () => {
    // Возврат — тоже покупка, и в часах он стоит столько же.
    expect(formatWorkCost(-2100, 500)).toBe("4,2 ч");
  });

  it("без ставки и на нулевой сумме отвечает пусто", () => {
    expect(formatWorkCost(1000, null)).toBeNull();
    expect(formatWorkCost(1000, 0)).toBeNull();
    expect(formatWorkCost(0, 500)).toBeNull();
  });

  it("на нечисле не выдумывает значение", () => {
    expect(formatWorkCost("не число", 500)).toBeNull();
  });

  it("единицы переводятся вместе с языком", () => {
    setLanguage("en");
    expect(formatWorkCost(250, 500)).toContain("min");
    expect(formatWorkCost(1000, 500)).toMatch(/2\.0/);
  });
});
