/**
 * Ключ строки формы — для React, а не для криптографии.
 *
 * Раньше здесь звался `crypto.randomUUID()`, и это ломало приложение ровно
 * там, где его чаще всего и разворачивают дома: браузер отдаёт `crypto` с
 * этим методом только в защищённом окружении — по https или на localhost.
 * Откройте установку по адресу в локальной сети (`http://192.168.1.10:3000`),
 * и страницы с формой операции и планов падали с пустым экраном, потому что
 * метода там просто нет.
 *
 * Нужна здесь лишь непохожесть на соседей в пределах одной формы: ключ живёт,
 * пока открыто окно, и никуда не сохраняется. Случайного числа со счётчиком
 * для этого достаточно, а `crypto.randomUUID` используется, когда он есть, —
 * не ради стойкости, а чтобы не плодить второй вид ключей.
 */
let counter = 0;

export function newRowKey(): string {
  counter += 1;
  const uuid = globalThis.crypto?.randomUUID;
  if (typeof uuid === "function") return globalThis.crypto.randomUUID();
  return `row-${counter}-${Math.random().toString(36).slice(2, 10)}`;
}
