import type { Transaction } from "@/types";

/**
 * Визуальная склейка одинаковых операций одного дня.
 *
 * Четыре поездки на автобусе за день — это четыре строки, отличающиеся
 * только временем ввода. По отдельности они не сообщают ничего, чего не
 * сказала бы одна строка «Автобус ×4 — 140 ₽», зато занимают весь экран и
 * прячут за собой всё остальное.
 *
 * Три решения, определяющие поведение:
 *
 *  * **склейка только визуальная.** Записи остаются отдельными: у каждой
 *    свой баланс, своя правка и своё удаление. Сливать их в одну строку в
 *    базе значило бы терять историю ради вида списка;
 *  * **склеивается всё совпадающее за день, а не только соседнее.** Между
 *    двумя поездками могла втиснуться покупка кофе, и от неё группировка
 *    зависеть не должна — иначе она то появляется, то исчезает без видимой
 *    причины;
 *  * **суммы могут отличаться.** Проезд дорожает, у одной поездки может
 *    быть другой тариф — совпадать обязаны счёт, тип, категория и описание,
 *    а сумма показывается общая.
 *
 * Ограничение, о котором стоит знать: группа не переходит границу страницы.
 * Если три поездки попали на одну страницу, а четвёртая на следующую, будет
 * «×3» и отдельная строка. Чинить это значило бы тянуть пагинацию на
 * сервер в группированном виде, что дороже пользы.
 */

export interface TransactionGroup {
  /** Ключ для React и для запоминания раскрытых групп. */
  key: string;
  /** Операции группы в том же порядке, в каком пришли из списка. */
  items: Transaction[];
  /** Строка, показываемая свёрнутой. Для группы из одной операции — она
   * сама, поэтому вызывающему коду не нужна отдельная ветка. */
  head: Transaction;
  /** Сумма по группе в валюте операций. */
  total: number;
}

/** Описание, приведённое к сравнимому виду: регистр и лишние пробелы не
 * должны мешать склейке — «Автобус» и «автобус  » это одно и то же. */
function normalize(description: string): string {
  return description.trim().toLowerCase().replace(/\s+/g, " ");
}

function groupKey(tx: Transaction): string {
  // Категория берётся с учётом разделения по нескольким категориям: чек,
  // разбитый на «Сладости» и «Алкоголь», не должен склеиваться с обычной
  // покупкой того же магазина на ту же сумму.
  const categoryPart = tx.splits.length > 0 ? `split:${tx.splits.map((s) => s.category_id).join(",")}` : `cat:${tx.category_id ?? "none"}`;
  return [
    tx.date,
    `acc:${tx.account_id}`,
    `type:${tx.type}`,
    categoryPart,
    `cur:${tx.currency}`,
    // Исключённые из расчётов не склеиваются с обычными: у них другой смысл
    // и другое поведение в суммах.
    `excl:${tx.is_excluded}`,
    `desc:${normalize(tx.description)}`,
  ].join("|");
}

/**
 * Собирает список в группы, сохраняя исходный порядок.
 *
 * Группа встаёт на место своей первой операции — так строка не «прыгает»
 * вверх списка от того, что к ней добавилась ещё одна поездка.
 */
export function groupTransactions(items: Transaction[], enabled: boolean): TransactionGroup[] {
  if (!enabled) {
    return items.map((tx) => ({ key: String(tx.id), items: [tx], head: tx, total: Number(tx.amount) }));
  }

  const groups = new Map<string, TransactionGroup>();

  for (const tx of items) {
    const key = groupKey(tx);
    const existing = groups.get(key);
    if (existing) {
      existing.items.push(tx);
      existing.total += Number(tx.amount);
    } else {
      groups.set(key, { key, items: [tx], head: tx, total: Number(tx.amount) });
    }
  }

  return [...groups.values()];
}
