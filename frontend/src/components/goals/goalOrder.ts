import type { Goal } from "@/types";

/** Сначала новые или сначала старые. */
export type GoalOrder = "newest" | "oldest";

/**
 * Дата, по которой цель занимает своё место в списке.
 *
 * У активной это дата создания: копится она прямо сейчас, и вопрос к списку —
 * «что я недавно затеял». У завершённой — дата сбора: закрытые цели читают
 * как историю, и последняя собранная интереснее той, что закрыли год назад.
 * Дата сбора может быть не заполнена у отменённой — тогда за неё отвечает
 * начало накопления, а в последнюю очередь дата создания: она есть всегда.
 */
function orderKey(goal: Goal): string {
  if (goal.status !== "active") return goal.closed_at ?? goal.started_on ?? goal.created_at;
  return goal.created_at;
}

/**
 * Цели по дате, а не по алфавиту.
 *
 * Сортируется здесь, а не на сервере, потому что здесь же стоит
 * переключатель направления: ходить за перестановкой списка в базу значит
 * ждать ответа ради того, что уже загружено.
 *
 * Строки дат сравниваются как строки: и «2025-04-09», и
 * «2026-09-08T19:39:52Z» начинаются с года, месяца и дня в одном и том же
 * виде, поэтому лексикографический порядок совпадает с хронологическим.
 */
export function sortGoals(goals: Goal[], order: GoalOrder): Goal[] {
  const direction = order === "newest" ? -1 : 1;
  return [...goals].sort((first, second) => {
    const left = orderKey(first);
    const right = orderKey(second);
    if (left !== right) return (left < right ? -1 : 1) * direction;
    // Одинаковая дата — по номеру записи: у целей, перенесённых из таблицы
    // одним заходом, дата создания одна на всех, и без номера они
    // выстраивались как придётся — на вид по алфавиту.
    return (first.id - second.id) * direction;
  });
}
