import { useIsDark } from "@/lib/theme";

/**
 * Фирменный знак: широкая плашка или квадратный значок.
 *
 * Раньше рисовался прямо здесь встроенным SVG — золотой монетой с засечной
 * «A», унаследованной от оригинального Aurum. Теперь это готовые файлы в
 * `public/brand`, а компонент только выбирает нужный и отводит ему место.
 *
 * Файлов по два на каждый вид: обсидиановый и мраморный. Выбор делает
 * разметка, а не CSS, — растровую картинку значением переменной не
 * перекрасишь. Показывать обе и прятать одну через display было бы проще,
 * но тогда браузер грузил бы оба файла, а это лишние сотни килобайт на
 * каждом заходе ради картинки, которую никто не увидит.
 *
 * Ширина не задаётся: у плашки и значка свои пропорции, и высоты
 * достаточно. Так замена файла на другой похожей формы ничего не ломает.
 */
interface LogoProps {
  /** «plate» — плашка со словом «Aurum-Ex», «icon» — квадратный знак. */
  variant?: "plate" | "icon";
  /** Высота в точках. */
  size?: number;
  className?: string;
}

export function Logo({ variant = "icon", size = 24, className }: LogoProps) {
  const isDark = useIsDark();
  const tone = isDark ? "dark" : "marble";
  const src = `/brand/${variant === "plate" ? "plate" : "icon"}-${tone}.png`;

  return (
    <img
      src={src}
      alt="Aurum-Ex"
      // Высота задана, ширина считается сама. width намеренно не выставлен:
      // пропорции у файлов разные, и жёсткое число растянуло бы один из них.
      style={{ height: size, width: "auto" }}
      className={className}
      // Знак стоит в шапке и нужен в первом кадре — отложенная загрузка
      // дала бы прыжок разметки на каждом заходе.
      decoding="sync"
    />
  );
}
