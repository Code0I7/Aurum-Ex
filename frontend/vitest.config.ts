import { fileURLToPath } from "node:url";
import { defineConfig } from "vitest/config";

/**
 * Отдельный файл, а не раздел в vite.config.ts, намеренно: конфигурация
 * сборки приложения от присутствия тестов не меняется ни на строку.
 *
 * Окружение — node, не jsdom. Проверяется чистая логика: разбор выписки,
 * склонение числительных, цена покупки в рабочих часах, расчёт доходности.
 * Для неё браузер не нужен, а jsdom — десять мегабайт зависимости и
 * медленный старт. Когда дойдёт дело до тестов самих компонентов, jsdom
 * добавится вместе с ними.
 */
export default defineConfig({
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
    },
  },
  test: {
    environment: "node",
    env: {
      // Часовой пояс прибит, и не ради единообразия, а потому что в UTC
      // половина ошибок с датами невидима. Дата собирается из местных
      // частей (см. isoDate в lib/dateRange.ts); если кто-нибудь вернёт
      // вместо этого toISOString, в UTC всё сойдётся, а восточнее
      // Гринвича ранним утром «по сегодня» начнёт терять сегодняшний день.
      // На сдвинутом поясе такая правка падает сразу.
      //
      // Москва: сдвиг положительный, перехода на летнее время нет, и это
      // тот самый пояс, в котором приложением пользуются.
      TZ: "Europe/Moscow",
    },
    include: ["src/**/*.test.ts"],
    // Хранилище браузера, которого в node нет. Модуль i18n читает язык из
    // localStorage прямо при загрузке — без заглушки падал бы любой тест,
    // который его втягивает, а втягивает его почти всё.
    setupFiles: ["./src/test/setup.ts"],
  },
});
