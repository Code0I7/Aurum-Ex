"""Автоматическая раскладка плоского списка категорий по смыслу.

В самодельной таблице дерево было ровно двухуровневым, потому что глубже
она не умела: 32 ветки и 123 листа в одной плоскости. Часть группировок
человек уже выразил — прямо в названиях, через тире («Электроника —
Аксессуары», «Электроника — Комплектующие»), — а часть держал в голове.

Здесь и то и другое превращается в дерево. Две ступени, и они принципиально
разного качества:

**Первая — по общему началу имени.** Это не догадка вовсе, а чтение того,
что человек уже написал: две ветки с общим началом до тире объединяются под
ним. Одиночная ветка обёртку не получает — она была бы лишним уровнем ни
для чего.

**Вторая — по смыслу.** Вот это догадка, и она честно так и называется.
Двадцать одна подкатегория продуктов в одном списке нечитаема, и разложить
её на напитки, сладкое, консервы — очевидно полезно; но где именно проходит
граница между «десертом» и «выпечкой», знает только владелец. Поэтому
результат показывается до импорта и правится руками.

Чего здесь намеренно нет: переименований. Раскладка добавляет уровни, но не
трогает ни одного существующего названия — человек ищет свои категории по
именам, которые сам придумал, и «улучшенное» имя означает, что он их больше
не найдёт.
"""
from collections import defaultdict
from dataclasses import dataclass, field

# Разделители, которыми человек уже выразил иерархию в плоском имени.
# Пробелы вокруг обязательны: «18+» и «Кофе-брейк» разделителя не содержат.
PREFIX_SEPARATORS = (" - ", " — ", " – ")

# Сколько веток должны разделить общее начало, чтобы обёртка имела смысл.
MIN_SHARED_PREFIX = 2

# С какого числа детей плоский список перестаёт читаться и его стоит
# разложить. Двадцать одна строка продуктов — точно да, три строки мебели —
# точно нет.
MIN_CHILDREN_TO_GROUP = 8

# Сколько детей должна собрать смысловая группа, чтобы её заводить. Группа
# из одного элемента — это тот же элемент плюс лишний уровень.
MIN_GROUP_SIZE = 2

# Смысловые группы: название группы → слова, по которым в неё попадают.
# Проверяется вхождение в нижнем регистре, поэтому «Соки» ловится по «сок».
#
# Список намеренно короткий и бытовой. Пытаться покрыть им всё — значит
# получить группы вроде «Прочее-2», а разложить остаток человек и сам
# сможет: он для этого и смотрит результат.
SEMANTIC_GROUPS: dict[str, tuple[str, ...]] = {
    "Напитки": ("сок", "газиров", "компот", "кофе", "чай", "вода", "морс", "лимонад", "квас"),
    "Сладкое": (
        "печень",
        "пряник",
        "круасан",
        "круассан",
        "торт",
        "пироженн",
        "пирожн",
        "кекс",
        "халва",
        "рахат",
        "козинак",
        "десерт",
        "мороженн",
        "шоколад",
        "конфет",
        "варень",
    ),
    "Молочное": ("кефир", "молоко", "йогурт", "творог", "сметан", "сыр", "ряженк"),
    "Консервы": ("консерв", "тушёнк", "тушенк", "паштет"),
    "Хлеб и выпечка": ("хлеб", "батон", "лаваш", "булк", "выпечк"),
    "Мясное": ("колбас", "сосиск", "мясо", "курин", "фарш", "ветчин", "бекон"),
    "Овощи и фрукты": ("овощ", "фрукт", "зелень", "салат", "ягод", "сухофрукт"),
    "Бакалея": ("макарон", "крупа", "мука", "сахар", "соль", "масло", "соус", "специ", "яйц"),
    "Снеки": ("чипс", "сухарик", "гренк", "орех", "семечк", "снек"),
}


def split_prefix(name: str) -> tuple[str, str] | None:
    """Делит «Электроника — Аксессуары» на («Электроника», «Аксессуары»).

    None, когда разделителя нет или одна из половин пуста: «— Прочее» и
    «Ремонт —» это опечатки, а не иерархия.
    """
    for separator in PREFIX_SEPARATORS:
        if separator in name:
            head, _, tail = name.partition(separator)
            head, tail = head.strip(), tail.strip()
            if head and tail:
                return head, tail
    return None


def group_by_shared_prefix(names: list[str]) -> dict[str, str]:
    """Ветки, чьи имена начинаются одинаково, собираются под общим началом.

    Возвращает «имя ветки → имя её нового родителя». Родителя, совпадающего
    с уже существующей веткой, не создаём заново — он просто становится
    родителем остальных.

    Это не догадка, а чтение того, что человек уже написал: он сам назвал
    две ветки «Электроника — Аксессуары» и «Электроника — Комплектующие».
    """
    by_prefix: dict[str, list[str]] = defaultdict(list)
    for name in names:
        parts = split_prefix(name)
        if parts is not None:
            by_prefix[parts[0]].append(name)

    assignment: dict[str, str] = {}
    existing = set(names)
    for prefix, children in by_prefix.items():
        # Ветка, чьё имя совпадает с началом, сама становится родителем: под
        # «Долги» уходят «Долги — Погашение» и «Долги — Возврат», а не под
        # второй, только что придуманный «Долги».
        real_children = [name for name in children if name != prefix]
        if len(real_children) < MIN_SHARED_PREFIX and prefix not in existing:
            continue
        if not real_children:
            continue
        for name in real_children:
            assignment[name] = prefix
    return assignment


def group_by_meaning(children: list[str]) -> dict[str, str]:
    """Раскладывает длинный список листьев по смысловым группам.

    Возвращает «имя листа → имя группы». Лист, не попавший ни в одну группу,
    в результат не входит и остаётся на своём месте: «Прочее» из остатков —
    это папка, в которую никто никогда не заглядывает.

    Догадка, и осознанная: где проходит граница между десертом и выпечкой,
    знает только владелец. Поэтому результат показывается до импорта.
    """
    if len(children) < MIN_CHILDREN_TO_GROUP:
        return {}

    matched: dict[str, str] = {}
    for name in children:
        lowered = name.lower()
        for group, keywords in SEMANTIC_GROUPS.items():
            if any(keyword in lowered for keyword in keywords):
                matched[name] = group
                break

    # Группы из одного элемента отбрасываем: это тот же элемент плюс лишний
    # уровень.
    counts: dict[str, int] = defaultdict(int)
    for group in matched.values():
        counts[group] += 1
    return {name: group for name, group in matched.items() if counts[group] >= MIN_GROUP_SIZE}


@dataclass
class NestingPlan:
    """Что и куда переезжает.

    Ключ — не имя, а пара «ветка, лист» из таблицы. Имена в этом дереве не
    уникальны, и совпадения встречаются сплошь и рядом: ветка «Вода» с
    подкатегорией «Вода» (так в таблице обозначали трату на ветку без
    уточнения) при раскладке по именам делала категорию родителем самой
    себе.
    """

    # Ветка верхнего уровня → новый родитель над ней (или None).
    branch_parent: dict[str, str | None] = field(default_factory=dict)
    # Пара (ветка, лист) → смысловая группа внутри ветки (или None).
    leaf_group: dict[tuple[str, str], str | None] = field(default_factory=dict)
    # Новые промежуточные уровни → их родитель. Порядок вставки таков, что
    # родитель всегда объявлен раньше ребёнка.
    new_levels: dict[str, str | None] = field(default_factory=dict)


def build_nesting(tree: dict[str, list[str]]) -> NestingPlan:
    """Полная раскладка плоского дерева «ветка → её листья».

    Порядок ступеней важен: сперва ветки собираются по общему началу имени
    (это факт), и только потом длинные списки листьев разбиваются по смыслу
    (это догадка). Обратный порядок смешал бы одно с другим.
    """
    plan = NestingPlan()

    prefix_parents = group_by_shared_prefix(list(tree))
    for branch in tree:
        plan.branch_parent[branch] = prefix_parents.get(branch)
    for new_parent in prefix_parents.values():
        if new_parent not in tree:
            plan.new_levels.setdefault(new_parent, None)

    for branch, children in tree.items():
        groups = group_by_meaning(children)
        for child in children:
            group = groups.get(child)
            if group is None:
                plan.leaf_group[(branch, child)] = None
                continue
            # Группа живёт внутри своей ветки: «Напитки» под продуктами и
            # «Напитки» под бытовой химией — разные вещи, и склеивать их по
            # имени нельзя.
            group_name = f"{branch} \u00b7 {group}"
            plan.new_levels.setdefault(group_name, branch)
            plan.leaf_group[(branch, child)] = group_name

    return plan
